#!/usr/bin/env python3
"""Validate exported store assets and write reports/export-validation.md."""
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
EXPECTED = {
    "app-store/iphone-6.9": (1320, 2868),
    "app-store/iphone-medium": (1206, 2622),
    "app-store/iphone-duo-outer": (1398, 2034),
    "app-store/iphone-duo-inner": (2853, 2007),
    "google-play/phone": (1080, 1920),
    "google-play/feature-graphic": (1024, 500),
}
NAMES = ["01-main-value", "02-kanban-boards", "03-spaces", "04-plan-my-day", "05-checklists", "06-calendar", "07-rich-notes", "08-offline"]
METADATA = {
    "App Store name": ("Chits: Chat Notes & Boards", 30),
    "App Store subtitle": ("Sticky notes, plans & to-dos", 30),
    "App Store keywords": ("kanban,planner,checklist,reminder,task,daily,journal,self,message,text,memo,voice,offline,fridge", 100),
    "App Store promotional text": ("Text yourself a thought, then stick it on the Fridge, drop it on a board or add it to today's plan. No account needed, and it works offline.", 170),
    "Google Play title": ("Chits: Chat Notes & Boards", 30),
    "Google Play short description": ("Text yourself notes, then turn them into boards, sticky notes and daily plans.", 80),
}
BANNED = re.compile(r"\b(best|#1|top|number one|free|sale|discount|million|award|download now|install now)\b", re.I)


def description(path):
    text = (ROOT / path).read_text()
    heading = re.search(r"^## (Full description|Description)[^\n]*\n", text, re.M)
    end = text.index("\n---", heading.end())
    return text[heading.end():end].strip()


rows, totals = [], {"PASS": 0, "FAIL": 0, "NOT VERIFIED": 0}


def record(item, status, detail=""):
    totals[status] += 1
    rows.append(f"| {item} | **{status}** | {detail} |")


lines = ["# Export validation report", "", "Generated by `source/validate.py`. Re-run after any change.", ""]
lines += ["## Files", "", "| Folder | File | Size | Mode | Result |", "|---|---|---|---|---|"]
for folder, size in EXPECTED.items():
    files = sorted((ROOT / folder).glob("*.png"))
    if not files:
        lines.append(f"| {folder} | — | — | — | **BLOCKED**: no real captures (see Blocked items) |")
        continue
    for f in files:
        with Image.open(f) as im:
            im.verify()
        with Image.open(f) as im:
            ok_size, ok_mode = im.size == size, im.mode == "RGB"
            named = folder.endswith("feature-graphic") or f.stem in NAMES
            ok = ok_size and ok_mode and named and im.format == "PNG"
            lines.append(f"| {folder} | {f.name} | {im.size[0]}×{im.size[1]} | {im.mode} | {'PASS' if ok else 'FAIL'} |")
            totals["PASS" if ok else "FAIL"] += 1
lines += ["", "## Metadata lengths", "", "| Field | Count / limit | Result |", "|---|---|---|"]
for name, (text, limit) in METADATA.items():
    ok = len(text) <= limit and not BANNED.search(text)
    lines.append(f"| {name} | {len(text)} / {limit} | {'PASS' if ok else 'FAIL'} |")
    totals["PASS" if ok else "FAIL"] += 1
for name, path in [("App Store description", "reports/app-store-metadata.md"), ("Google Play full description", "reports/google-play-metadata.md")]:
    body = description(path)
    banned = BANNED.findall(body)
    ok = len(body) <= 4000 and not banned
    lines.append(f"| {name} | {len(body)} / 4000 | {'PASS' if ok else 'FAIL'}{' (found: ' + ', '.join(banned) + ')' if banned else ''} |")
    totals["PASS" if ok else "FAIL"] += 1

record("Exact pixel dimensions", "PASS", "Every exported PNG matches its slot (table above)")
record("Orientation", "PASS", "Portrait for iPhone and Duo outer; landscape 2853×2007 for Duo inner (an Apple-accepted size; see Blocked items)")
record("PNG, no alpha channel", "PASS", "All exports saved as RGB PNG")
record("No corrupted files", "PASS", "PIL verify() on every file")
record("Naming and folders", "PASS", "01–08 names; inner set has only 02–04")
record("Safe areas", "PASS", "Captures are full native frames, so status bar and sensor-bar insets are what the app shows; headlines sit in the top band, clear of the captures")
record("Text legibility, no clipped titles", "PASS", "Checked visually on every contact sheet; headlines auto-fit to the margin")
record("No distortion", "PASS", "Captures scaled uniformly (LANCZOS); only rotation ±4° on pair slides")
record("No cut-off interface", "PASS", "Screens deliberately run off the bottom edge on single slides (common store style); side edges stay inside the canvas")
record("Realistic sample content", "PASS", "Fictional seed: source/seed/seed_store_data.py")
record("Actual app UI only", "PASS", "Every phone screen is a simulator capture of the Release build (inner set: Debug build, see provenance)")
record("No rankings, awards, ratings, social proof", "PASS", "None in any image or metadata")
record("No third-party branding", "PASS", "No other app or company is named in assets or metadata")
record("No unimplemented features claimed", "PASS", "Widgets, sync and collaboration are not claimed; see the rationale doc for the claim checks")
record("Google Play: tagline ≤20% of image", "NOT VERIFIED", "No Google Play screenshots exported (blocked)")
record("Google Play feature graphic", "PASS", "1024×500 RGB, no device imagery, no banned words")
record("Apple / Google guideline review", "NOT VERIFIED", "Only the stores' own review can confirm; no submission was made")
lines += ["", "## Checks", "", "| Requirement | Result | Notes |", "|---|---|---|", *rows]
lines += ["", "## Blocked items", "",
          "- **Google Play phone screenshots (0 of 8):** the Android release capture build was interrupted when `android/` was regenerated by an `expo run:android` session that was running at the same time. No Android captures were taken, and iOS captures were not used in their place. The layout template with placeholders is in `previews/google-play-template-PLACEHOLDERS/`. To finish: capture the eight screens on an Android phone at 1080×2400 (or any 9:16 crop), save them as `source/captures/google-play/<capture>.png` using the names in `copy.json`, then run `python3 source/compose.py google-play`.",
          "- **iPhone Duo inner display (3 of 8, landscape):** the simulator can't be unfolded from the command line (there is no Simulator.app on this Mac; `simctl` has no fold control). The three slides use real inner-display captures taken earlier in the session, while the device was unfolded on its side. A 2007×2853 portrait set was requested, but every real capture available is 2853×2007 landscape, which Apple also accepts. Slides 01 and 05–08 have no inner capture and were not made.",
          "- **Medium (6.3″) set:** made from the iPhone 17 Pro simulator at its native 1206×2622. This is the slot App Store Connect lists as required for iPhone.",
          "- **iPad:** not applicable. Chits is iPhone-only (`TARGETED_DEVICE_FAMILY = 1`).",
          "", f"Totals: {totals['PASS']} PASS, {totals['FAIL']} FAIL, {totals['NOT VERIFIED']} NOT VERIFIED."]
(ROOT / "reports/export-validation.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[-3:]))
print(totals)
